"""Run real stdio calls with the official MCP Python SDK in an isolated QA venv.

The client imports no application code. Fixtures are generated by the app Python
in a separate process, and the MCP server is another independent subprocess.
"""

import argparse
import asyncio
import hashlib
from importlib.metadata import version
import json
from pathlib import Path
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]


def make_fixtures(directory):
    sys.path.insert(0, str(ROOT))
    from mazeproof.samples import demo_model, demo_route, render
    from PIL import ImageDraw

    directory.mkdir(parents=True, exist_ok=True)
    model = demo_model()
    (directory / "problem.json").write_text(json.dumps(model))
    render(model).save(directory / "problem.png")
    render(model, demo_route()).save(directory / "solution.png")
    faint = render(model)
    ImageDraw.Draw(faint).line((96, 168, 130, 168), fill=(160, 160, 160), width=7)
    faint.save(directory / "faint.png")
    (directory / "broken.png").write_bytes(b"not an image")
    render(model).save(
        directory / "pair.pdf",
        "PDF",
        save_all=True,
        append_images=[render(model, demo_route())],
    )


async def check(args):
    from mcp import Client
    from mcp.client.stdio import StdioServerParameters

    output = Path(args.output).resolve()
    output.mkdir(parents=True, exist_ok=True)
    fixtures = output / "fixtures"
    subprocess.run(
        [args.server_python, __file__, "--fixtures-only", str(fixtures)],
        check=True,
        cwd=ROOT,
    )
    hashes = {
        p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in fixtures.iterdir()
    }
    params = StdioServerParameters(
        command=args.server_python,
        args=["-m", "mazeproof", "mcp", "--allow-root", str(fixtures)],
        cwd=str(ROOT),
    )
    checks = []
    started = time.monotonic()
    async with Client(params, read_timeout_seconds=120) as client:
        listing = await client.list_tools()
        assert {t.name for t in listing.tools} == {
            "validate_structure",
            "inspect_file",
            "validate_pair",
            "inspect_batch",
            "get_result",
        }
        assert all(t.annotations.read_only_hint for t in listing.tools)
        checks.append(
            "Official SDK initialized a real stdio server and discovered five read-only tools"
        )

        async def call(name, arguments, error=False):
            response = await client.call_tool(name, arguments)
            assert response.is_error is error, response
            return json.loads(response.content[0].text)["result"]

        structure = await call(
            "validate_structure",
            {
                "problem": (fixtures / "problem.json").read_text(),
            },
        )
        assert structure["overallStatus"] == "PASS"
        problem = str(fixtures / "problem.png")
        solution = str(fixtures / "solution.png")
        image = await call("inspect_file", {"path": problem})
        assert image["overallStatus"] == "NEEDS_REVIEW"
        pair = await call("validate_pair", {"problem": problem, "solution": solution})
        assert pair["overallStatus"] == "NEEDS_REVIEW"
        checks.append(
            "Exact structure PASS remains distinct from unconfirmed image and pair results"
        )
        batch = await call(
            "inspect_batch",
            {
                "items": [
                    {"id": "pair", "problem": problem, "solution": solution},
                    {"id": "faint", "problem": str(fixtures / "faint.png")},
                    {"id": "broken", "problem": str(fixtures / "broken.png")},
                    {"id": "outside", "problem": str(ROOT / "README.md")},
                    {"id": "inject-approval", "problem": problem, "confirmed": True},
                    {
                        "id": "pdf",
                        "problem": str(fixtures / "pair.pdf"),
                        "problem_page": 1,
                        "solution": str(fixtures / "pair.pdf"),
                        "solution_page": 2,
                    },
                ]
            },
        )
        assert batch["overallStatus"] == "NEEDS_REVIEW"
        assert batch["counts"] == {"NEEDS_REVIEW": 3, "ERROR": 3, "QUEUED": 0}
        items = {item["id"]: item for item in batch["items"]}
        assert items["pair"]["result"]["checks"] == pair["checks"]
        assert items["faint"]["result"]["evidence"]["provisionalStatus"] == "FAIL"
        assert all(item["result"]["overallStatus"] != "PASS" for item in batch["items"])
        assert "OUTSIDE_ALLOWED_ROOT" in json.dumps(items["outside"])
        cached = await call("get_result", {"requestId": batch["requestId"]})
        assert cached == batch
        checks.append(
            "Mixed PNG/pair/PDF batch isolates corrupt, outside-root and approval-injection errors; cached result agrees"
        )
        unknown = await call("approve", {"id": "pair"}, error=True)
        assert unknown["overallStatus"] == "INVALID_INPUT"
        checks.append("The client cannot approve images")

        hundred = await call(
            "inspect_batch",
            {"items": [{"id": str(i), "problem": problem} for i in range(100)]},
        )
        assert hundred["counts"] == {"NEEDS_REVIEW": 100, "ERROR": 0, "QUEUED": 0}
        assert all(
            row["result"]["overallStatus"] == "NEEDS_REVIEW" for row in hundred["items"]
        )
        checks.append("100 real image inspections complete with no unreviewed PASS")
        protocol = client.protocol_version
    after = {
        p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in fixtures.iterdir()
    }
    assert hashes == after
    checks.append(
        "All input files remain byte-identical; no host registration or permanent permissions changed"
    )
    evidence = {
        "client": "official MCP Python SDK",
        "sdkVersion": version("mcp"),
        "protocolVersion": protocol,
        "transport": "real stdio subprocess",
        "checks": checks,
        "count": len(checks),
        "seconds": round(time.monotonic() - started, 2),
        "mixedCounts": batch["counts"],
        "hundredCounts": hundred["counts"],
        "guiHostTested": False,
    }
    (output / "result.json").write_text(json.dumps(evidence, indent=2) + "\n")
    print(json.dumps(evidence, indent=2))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--server-python", default=str(ROOT / ".venv/bin/python"))
    parser.add_argument("--output", default=str(ROOT / ".evidence/mcp-client"))
    parser.add_argument("--fixtures-only", type=Path)
    args = parser.parse_args()
    if args.fixtures_only:
        make_fixtures(args.fixtures_only)
    else:
        asyncio.run(check(args))


if __name__ == "__main__":
    main()
